"""
Cross-Platform Demo — The "One Tool" Script
=============================================
THIS is the point of Appium.

This single script automates BOTH a web browser AND a desktop app,
using the same API, the same Python code style, the same Appium server.

Scenario this simulates:
1. Open Chrome → go to a website → scrape some data
2. Open Notepad → paste that data into a document
3. (Future: open Excel → paste into a spreadsheet)

This is the workflow pattern you'd use for:
- Pulling data from Deacom's web UI → pasting into Excel
- Reading a web report → entering values into a desktop ERP
- Any workflow that crosses the web/desktop boundary

PREREQUISITES:
  - Windows 10/11
  - Appium server running with both drivers installed
  - Developer Mode enabled
  - WinAppDriver installed
"""

import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from utils.driver_manager import DriverManager
from utils.wait_helpers import wait_and_type, wait_for_element, pause
from config.capabilities import CHROME_CAPS, NOTEPAD_CAPS


def run_cross_platform_demo():
    """
    Web → Desktop automation in one script.
    
    Step 1: Use Chrome to get today's date from timeanddate.com
    Step 2: Open Notepad and write a report with that data
    
    This proves the "one tool" concept — same framework, both platforms.
    """
    print("=" * 60)
    print("CROSS-PLATFORM DEMO — WEB + DESKTOP IN ONE SCRIPT")
    print("=" * 60)
    
    collected_data = {}
    
    # ============================================================
    # PHASE 1: Web Automation (Chrome)
    # ============================================================
    print("\n--- PHASE 1: Web Browser ---")
    print("Collecting data from a website...\n")
    
    with DriverManager(CHROME_CAPS) as web_driver:
        
        # Go to a simple page and grab some text
        web_driver.get("https://httpbin.org/get")
        pause(2, "Page loading")
        
        # Read the page content (httpbin returns JSON with request info)
        body = wait_for_element(web_driver, "tag_name", "pre")
        page_text = body.text
        
        # Extract the origin IP as sample "data" we collected
        import json
        try:
            data = json.loads(page_text)
            collected_data["ip"] = data.get("origin", "unknown")
            collected_data["user_agent"] = data.get("headers", {}).get("User-Agent", "unknown")
        except json.JSONDecodeError:
            collected_data["ip"] = "could not parse"
            collected_data["user_agent"] = "could not parse"
        
        print(f"  Collected IP: {collected_data['ip']}")
        print(f"  Collected UA: {collected_data['user_agent'][:50]}...")
        
        # Take a screenshot of what we found
        web_driver.save_screenshot(
            os.path.join(os.path.dirname(os.path.abspath(__file__)), 
                         "..", "screenshot_phase1_web.png")
        )
    
    print("\n  Chrome closed. Data collected. Moving to desktop...\n")
    
    # ============================================================
    # PHASE 2: Desktop Automation (Notepad)
    # ============================================================
    print("--- PHASE 2: Desktop App ---")
    print("Writing collected data into Notepad...\n")
    
    with DriverManager(NOTEPAD_CAPS) as desktop_driver:
        
        pause(1, "Notepad launching")
        
        # Find the text editor area
        try:
            editor = wait_for_element(desktop_driver, "name", "Text editor")
        except Exception:
            editor = wait_for_element(desktop_driver, "class_name", "Edit")
        
        # Write a report using the data we collected from the web
        report = (
            "=== AUTOMATED CROSS-PLATFORM REPORT ===\n"
            "\n"
            "This report was generated by a SINGLE Appium script that:\n"
            "  1. Opened Chrome and scraped data from a website\n"
            "  2. Opened Notepad and wrote this report\n"
            "\n"
            "--- Data Collected from Web ---\n"
            f"  IP Address: {collected_data['ip']}\n"
            f"  User Agent: {collected_data['user_agent']}\n"
            "\n"
            "--- Why This Matters ---\n"
            "This proves ONE framework (Appium) can automate:\n"
            "  - Web browsers (like Deacom's web UI)\n"
            "  - Desktop apps (like Excel, legacy ERPs)\n"
            "  - Both in the same workflow\n"
            "\n"
            "No Playwright needed. No PyAutoGUI needed.\n"
            "No SikuliX needed. Just Appium.\n"
            "\n"
            "=== END OF REPORT ===\n"
        )
        
        editor.send_keys(report)
        
        print("  Report written to Notepad!")
        
        # Screenshot the result
        desktop_driver.save_screenshot(
            os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "..", "screenshot_phase2_desktop.png")
        )
        
        pause(3, "Admire the result before closing")
        
        # Close Notepad without saving
        from selenium.webdriver.common.keys import Keys
        editor.send_keys(Keys.ALT, Keys.F4)
        pause(1, "Close dialog")
        
        try:
            from utils.wait_helpers import wait_and_click
            wait_and_click(desktop_driver, "name", "Don\u2019t Save")
        except Exception:
            try:
                wait_and_click(desktop_driver, "name", "Don't Save")
            except Exception:
                pass
    
    # ============================================================
    # DONE
    # ============================================================
    print("\n" + "=" * 60)
    print("CROSS-PLATFORM DEMO COMPLETE")
    print("")
    print("What just happened:")
    print("  1. Appium opened Chrome, hit a website, grabbed data")
    print("  2. Appium opened Notepad, wrote a report with that data")
    print("  3. Same Python code, same API, same framework")
    print("")
    print("Now imagine replacing:")
    print("  Chrome → Deacom web UI (pull PO data)")
    print("  Notepad → Excel desktop app (paste into spreadsheet)")
    print("  or → Another legacy ERP (enter data)")
    print("=" * 60)


if __name__ == "__main__":
    run_cross_platform_demo()
